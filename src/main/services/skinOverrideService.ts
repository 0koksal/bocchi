export interface SkinOverrideOptions {
  /** Skin indexes to cover (e.g. every skin + chroma index of the champion). */
  skinNums?: number[]
  /** Champion key, used as an extra hint for locating the skin0 bins. */
  championKey?: string
  /** Directory where generated files are cached. */
  cacheDir: string
  /** `companion` (default): tiny extra mod. `full`: one standalone copy of the package. */
  mode?: SkinOverrideMode
}

export type SkinOverrideMode = 'companion' | 'full'

export interface SkinOverrideReport {
  /** The package contains skin0 bins that SkinOverride can re-identify. */
  applicable: boolean
  /** Why the package was left alone (when applicable is false). */
  reason?: string
  /** Number of bins added (0 when the variant came from the cache). */
  generated: number
  /** The variant already existed in the cache. */
  cached?: boolean
  /** Skin index the package was rebased from (e.g. 28 for Arcane Enforcer Caitlyn). */
  sourceSkinNum?: number
  /** `companion`: apply `outputPath` IN ADDITION to the original. `full`: use it INSTEAD. */
  mode: SkinOverrideMode
  /** File generated by SkinOverride. Equals the input path when not applicable. */
  outputPath: string
}

type Compressor = (data: Buffer) => Buffer

/** zstd is the codec the game's own WAD entries use; it keeps the ~100 near-identical copies small. */
const zstdCompress: Compressor = (data) => Buffer.from(compress(data, { compressionLevel: 12 }))

/** Fallback when the caller has no skin list: covers every index any champion currently has. */
const DEFAULT_SKIN_RANGE = Array.from({ length: 99 }, (_, i) => i + 1)

const BIN_DEP_RE = /^data\/characters\/([^/]+)\/(skins|animations)\/skin(\d+)\.bin$/i

// ── hashing ──────────────────────────────────────────────────────────────────

/** FNV-1a 32 of a lowercased string — how bin object paths are hashed. */
function fnv1a32(input: string): number {
  const s = input.toLowerCase()
  let h = 0x811c9dc5
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i)
    h = Math.imul(h, 0x01000193) >>> 0
  }
  return h >>> 0
}

function wadHash(pathText: string): bigint {
  return BigInt('0x' + xxhash64(pathText))
}

// ── PROP bin helpers ─────────────────────────────────────────────────────────

interface BinHeader {
  version: number
  dependencies: string[]
  /** Offset of the first byte after the dependency block. */
  bodyStart: number
}

/** Read only the header of a PROP bin (version + linked bins). Returns null if not a PROP bin. */
function readBinHeader(buf: Buffer): BinHeader | null {
  if (buf.length < 12 || buf.toString('latin1', 0, 4) !== 'PROP') return null
  const version = buf.readUInt32LE(4)
  if (version < 1 || version > 3) return null
  let pos = 8
  const dependencies: string[] = []
  if (version >= 2) {
    const count = buf.readUInt32LE(pos)
    pos += 4
    for (let i = 0; i < count; i++) {
      const len = buf.readUInt16LE(pos)
      pos += 2
      dependencies.push(buf.toString('latin1', pos, pos + len))
      pos += len
    }
  }
  return { version, dependencies, bodyStart: pos }
}

/**
 * Re-identify a skin0 bin as skinN.
 *
 * Replaces the 32-bit path hashes of `characters/<char>/{skins,animations}/skin0[/resources]`
 * (object ids and the references to them) and renames linked `…/skin0.bin` dependencies.
 * Everything else — including links to the real skin bins (e.g. skin28.bin) — is untouched.
 */
function retargetBin(buf: Buffer, header: BinHeader, chars: string[], n: number): Buffer {
  const body = Buffer.from(buf.subarray(header.bodyStart))

  for (const c of chars) {
    for (const kind of ['skins', 'animations']) {
      for (const suffix of ['', '/resources']) {
        const from = fnv1a32(`characters/${c}/${kind}/skin0${suffix}`)
        const to = fnv1a32(`characters/${c}/${kind}/skin${n}${suffix}`)
        for (let i = 0; i + 4 <= body.length; i++) {
          if (body.readUInt32LE(i) === from) {
            body.writeUInt32LE(to, i)
            i += 3
          }
        }
      }
    }
  }

  const parts: Buffer[] = [buf.subarray(0, 8)]
  if (header.version >= 2) {
    const count = Buffer.alloc(4)
    count.writeUInt32LE(header.dependencies.length)
    parts.push(count)
    for (const dep of header.dependencies) {
      const renamed = dep.replace(/\/skin0\.bin$/i, `/skin${n}.bin`)
      const len = Buffer.alloc(2)
      len.writeUInt16LE(renamed.length)
      parts.push(len, Buffer.from(renamed, 'latin1'))
    }
  }
  parts.push(body)
  return Buffer.concat(parts)
}

// ── WAD handling ─────────────────────────────────────────────────────────────

/**
 * Random-access view of a WAD. Scanning a package only needs its header, entry table and a few
 * small bins, so big custom mods (models, textures: 50-200 MB) are never loaded into memory.
 */
interface WadSource {
  size: number
  read(offset: number, length: number): Promise<Buffer>
}

const bufferSource = (buf: Buffer): WadSource => ({
  size: buf.length,
  read: async (offset, length) => buf.subarray(offset, offset + length)
})

/** Ranged reads straight from a file on disk (a raw .wad, or a STORE-d entry of a zip). */
async function withFileRange<T>(
  filePath: string,
  base: number,
  size: number,
  fn: (source: WadSource) => Promise<T>
): Promise<T> {
  const fh = await fs.open(filePath, 'r')
  try {
    return await fn({
      size,
      read: async (offset, length) => {
        const buf = Buffer.alloc(length)
        const { bytesRead } = await fh.read(buf, 0, length, base + offset)
        return bytesRead === length ? buf : buf.subarray(0, bytesRead)
      }
    })
  } finally {
    await fh.close()
  }
}

/**
 * Visit every WAD of a .fantome/.zip for scanning. STORE-d entries are read in place with ranged
 * reads; deflated ones are streamed once and only their small bins are kept in memory.
 */
async function forEachZipWad<T>(
  zipPath: string,
  visit: (entryName: string, source: WadSource) => Promise<T>
): Promise<T[]> {
  const results: T[] = []
  const zip = new StreamZip.async({ file: zipPath })
  try {
    for (const entry of Object.values(await zip.entries())) {
      const name = entry.name.replaceAll('\\', '/')
      if (entry.isDirectory || !/^WAD\/.+\.WAD(\.CLIENT)?$/i.test(name)) continue
      if (entry.method === 0) {
        const fh = await fs.open(zipPath, 'r')
        let dataStart: number
        try {
          const lfh = Buffer.alloc(30)
          await fh.read(lfh, 0, 30, entry.offset)
          dataStart = entry.offset + 30 + lfh.readUInt16LE(26) + lfh.readUInt16LE(28)
        } finally {
          await fh.close()
        }
        results.push(await withFileRange(zipPath, dataStart, entry.size, (src) => visit(name, src)))
      } else {
        const stream = await zip.stream(entry)
        results.push(await visit(name, await sequentialSource(stream, entry.size)))
      }
    }
  } finally {
    await zip.close()
  }
  return results
}

/** Bins are small: big chunks (models, textures, audio) are never read or decoded. */
const isBinCandidate = (entry: WadEntry): boolean =>
  entry.decompressedSize <= 512 * 1024 && entry.compressedSize >= 12

function decodeChunk(entry: WadEntry, raw: Buffer): Buffer | null {
  const compression = entry.typeByte & 0x0f
  try {
    if (compression === WAD_COMPRESSION.RAW) return raw
    if (compression === WAD_COMPRESSION.GZIP) return zlib.gunzipSync(raw)
    if (compression === WAD_COMPRESSION.ZSTD || compression === WAD_COMPRESSION.ZSTD_CHUNKED) {
      return Buffer.from(fzstd.decompress(new Uint8Array(raw)))
    }
  } catch {
    // unreadable chunk — not a bin we can use
  }
  return null
}

async function readChunk(source: WadSource, entry: WadEntry): Promise<Buffer | null> {
  try {
    return decodeChunk(entry, await source.read(entry.offset, entry.compressedSize))
  } catch {
    return null
  }
}

const isPropBin = (buf: Buffer | null): boolean =>
  !!buf && buf.length >= 4 && buf.toString('latin1', 0, 4) === 'PROP'

/**
 * A WAD source over a *sequential* stream (a deflated zip entry), for scanning only.
 * The stream is consumed once; only the header, the entry table and the chunks that really are
 * PROP bins are kept. Everything else (models, textures, audio) is dropped as it goes by, so a
 * 150 MB mod costs a few MB of memory instead of 150. Other reads are refused.
 */
async function sequentialSource(
  stream: AsyncIterable<Buffer | string>,
  size: number
): Promise<WadSource> {
  const kept = new Map<string, Buffer>()
  let head = Buffer.alloc(0)
  let headLen = 0
  type Range = { entry: WadEntry; start: number; end: number; buf: Buffer }
  let ranges: Range[] = []
  let lo = 0
  let pos = 0

  const finish = (r: Range): void => {
    if (isPropBin(decodeChunk(r.entry, r.buf))) kept.set(`${r.start}:${r.end - r.start}`, r.buf)
  }
  const feed = (chunk: Buffer, start: number): void => {
    const end = start + chunk.length
    for (let i = lo; i < ranges.length && ranges[i].start < end; i++) {
      const r = ranges[i]
      const s = Math.max(r.start, start)
      const e = Math.min(r.end, end)
      if (e > s) chunk.copy(r.buf, s - r.start, s - start, e - start)
    }
    while (lo < ranges.length && ranges[lo].end <= end) {
      finish(ranges[lo])
      ranges[lo].buf = Buffer.alloc(0) // release
      lo++
    }
  }

  const pending: Buffer[] = []
  let pendingLen = 0
  let ready = false
  for await (const part of stream) {
    const chunk = Buffer.isBuffer(part) ? part : Buffer.from(part)
    if (!ready) {
      pending.push(chunk)
      pendingLen += chunk.length
      if (headLen === 0 && pendingLen >= 272) {
        const first = Buffer.concat(pending)
        if (first[0] !== 0x52 || first[1] !== 0x57 || first[2] !== 3) break
        headLen = 272 + first.readUInt32LE(268) * 32
      }
      if (headLen === 0 || pendingLen < headLen) continue
      const all = Buffer.concat(pending)
      head = Buffer.from(all.subarray(0, headLen))
      const info = parseWad(head)
      if (!info) break
      ranges = info.entries
        .filter(isBinCandidate)
        .map((entry) => ({
          entry,
          start: entry.offset,
          end: entry.offset + entry.compressedSize,
          buf: Buffer.alloc(entry.compressedSize)
        }))
        .sort((a, b) => a.start - b.start)
      ready = true
      feed(all, 0)
      pos = all.length
      pending.length = 0
    } else {
      feed(chunk, pos)
      pos += chunk.length
    }
  }
  // chunks that ran past the end of a truncated stream are simply not kept
  return {
    size,
    read: async (offset, length) => {
      if (offset + length <= head.length) return head.subarray(offset, offset + length)
      const hit = kept.get(`${offset}:${length}`)
      if (!hit) throw new Error('chunk not retained')
      return hit
    }
  }
}

/** Write a v3 WAD from `entries` of `original` (may be none) plus new zstd entries. */
function buildWadWithAdditions(
  original: Buffer,
  entries: WadEntry[],
  added: Map<bigint, Buffer>,
  compress: Compressor
): Buffer {
  const headerSize = 4 + 256 + 8 + 4
  type Out = { hash: bigint; data: Buffer; entry: WadEntry }
  const all: Out[] = entries.map((e) => ({
    hash: e.hash,
    data: original.subarray(e.offset, e.offset + e.compressedSize),
    entry: e
  }))
  for (const [hash, plain] of added) {
    const data = compress(plain)
    all.push({
      hash,
      data,
      entry: {
        hash,
        offset: 0,
        compressedSize: data.length,
        decompressedSize: plain.length,
        typeByte: WAD_COMPRESSION.ZSTD,
        tail: Buffer.alloc(11) // zero checksum: readers compute it lazily
      }
    })
  }
  all.sort((a, b) => (a.hash < b.hash ? -1 : a.hash > b.hash ? 1 : 0))

  const dataStart = headerSize + all.length * 32
  const total = all.reduce((sum, o) => sum + o.data.length, dataStart)
  const out = Buffer.alloc(total)
  original.copy(out, 0, 0, headerSize - 4)
  out.writeUInt32LE(all.length, headerSize - 4)

  let offset = dataStart
  all.forEach((o, i) => {
    const p = headerSize + i * 32
    out.writeBigUInt64LE(o.hash, p)
    out.writeUInt32LE(offset, p + 8)
    out.writeUInt32LE(o.entry.compressedSize, p + 12)
    out.writeUInt32LE(o.entry.decompressedSize, p + 16)
    out.writeUInt8(o.entry.typeByte, p + 20)
    o.entry.tail.copy(out, p + 21)
    o.data.copy(out, offset)
    offset += o.data.length
  })
  return out
}

interface WadResult {
  wad: Buffer | null
  generated: number
  sourceSkinNum?: number
  reason?: string
}

interface Template {
  char: string
  kind: 'skins' | 'animations'
  buf: Buffer
  header: BinHeader
}

interface WadScan {
  info: NonNullable<ReturnType<typeof parseWad>>
  byHash: Map<bigint, number>
  chars: Set<string>
  templates: Template[]
  /** Skin the package was rebased from (e.g. 28), if its skin0 bin links to one. */
  sourceSkinNum?: number
}

/** Find the skin0 bins SkinOverride can re-identify inside a WAD (no output is produced). */
async function scanWad(
  source: WadSource,
  hintChamps: string[]
): Promise<WadScan | { reason: string }> {
  if (source.size < 272) return { reason: 'not a v3 WAD' }
  const head = await source.read(0, 272)
  if (head[0] !== 0x52 || head[1] !== 0x57 || head[2] !== 3) return { reason: 'not a v3 WAD' }
  const table = await source.read(272, head.readUInt32LE(268) * 32)
  const info = parseWad(Buffer.concat([head, table]))
  if (!info) return { reason: 'not a v3 WAD' }

  const byHash = new Map<bigint, number>()
  info.entries.forEach((e, i) => byHash.set(e.hash, i))

  // 1. Find the character folders the package talks about. Every skin bin links its
  //    animation bin by plaintext path, so the dependency lists name all of them
  //    (including helper characters such as "caitlyntrap").
  const chars = new Set<string>(hintChamps.map((c) => c.toLowerCase()))
  const binCache = new Map<number, { buf: Buffer; header: BinHeader }>()
  for (const [index, entry] of info.entries.entries()) {
    if (!isBinCandidate(entry)) continue
    const chunk = await readChunk(source, entry)
    if (!chunk) continue
    const header = readBinHeader(chunk)
    if (!header) continue
    binCache.set(index, { buf: chunk, header })
    for (const dep of header.dependencies) {
      const m = BIN_DEP_RE.exec(dep)
      if (m) chars.add(m[1].toLowerCase())
    }
  }

  // 2. Locate the skin0 templates inside the WAD.
  const templates: Template[] = []
  for (const char of chars) {
    for (const kind of ['skins', 'animations'] as const) {
      const idx = byHash.get(wadHash(`data/characters/${char}/${kind}/skin0.bin`))
      const cached = idx === undefined ? undefined : binCache.get(idx)
      if (cached) templates.push({ char, kind, ...cached })
    }
  }
  if (templates.length === 0) return { reason: 'no skin0 bins in package' }

  // 3. The skin the package was rebased from must not be overridden: its real bin is the
  //    dependency of our skin0 bin, and replacing it would make it link to itself.
  //    Standalone packages (a full copy of the skin inside skin0.bin) have no skins/skinN.bin
  //    link, so fall back to the animation bin they point at (animations/skinN.bin).
  let sourceSkinNum: number | undefined
  let animationHint: number | undefined
  for (const t of templates) {
    for (const dep of t.header.dependencies) {
      const m = BIN_DEP_RE.exec(dep)
      if (!m || m[1].toLowerCase() !== t.char || +m[3] === 0) continue
      if (m[2].toLowerCase() === 'skins') sourceSkinNum = +m[3]
      else animationHint = +m[3]
    }
  }
  sourceSkinNum ??= animationHint
  return { info, byHash, chars, templates, sourceSkinNum }
}

/** Re-identified copy of every template for every other skin index (hash -> plain bin). */
function planAdditions(scan: WadScan, skinNums: number[]): Map<bigint, Buffer> {
  const allChars = [...scan.chars]
  const added = new Map<bigint, Buffer>()
  for (const n of skinNums) {
    if (n === 0 || n === scan.sourceSkinNum) continue
    for (const t of scan.templates) {
      const hash = wadHash(`data/characters/${t.char}/${t.kind}/skin${n}.bin`)
      if (scan.byHash.has(hash)) continue // package already ships its own skinN bin
      added.set(hash, retargetBin(t.buf, t.header, allChars, n))
    }
  }
  return added
}

/**
 * Companion WAD: contains ONLY the added bins. Applied next to the untouched original mod it
 * costs a few hundred KB however big the skin is (the cslol overlay merges same-named WADs).
 */
async function buildCompanionWad(
  source: WadSource,
  skinNums: number[],
  hints: string[],
  compress: Compressor
): Promise<WadResult> {
  const scan = await scanWad(source, hints)
  if ('reason' in scan) return { wad: null, generated: 0, reason: scan.reason }
  const added = planAdditions(scan, skinNums)
  if (added.size === 0) {
    return { wad: null, generated: 0, reason: 'nothing to add', sourceSkinNum: scan.sourceSkinNum }
  }
  const header = Buffer.alloc(272)
  header.write('RW', 0, 'latin1')
  header[2] = 3
  header[3] = 3
  return {
    wad: buildWadWithAdditions(header, [], added, compress),
    generated: added.size,
    sourceSkinNum: scan.sourceSkinNum
  }
}

/** Full WAD: every original entry byte-for-byte plus the added bins (a single standalone file). */
async function buildFullWad(
  source: WadSource,
  skinNums: number[],
  hints: string[],
  compress: Compressor
): Promise<WadResult> {
  const scan = await scanWad(source, hints)
  if ('reason' in scan) return { wad: null, generated: 0, reason: scan.reason }
  const added = planAdditions(scan, skinNums)
  if (added.size === 0) {
    return { wad: null, generated: 0, reason: 'nothing to add', sourceSkinNum: scan.sourceSkinNum }
  }
  const data = await source.read(0, source.size)
  return {
    wad: buildWadWithAdditions(data, scan.info.entries, added, compress),
    generated: added.size,
    sourceSkinNum: scan.sourceSkinNum
  }
}

// ── public API ───────────────────────────────────────────────────────────────

function cacheKey(
  srcPath: string,
  stat: { size: number; mtimeMs: number },
  nums: number[],
  mode: SkinOverrideMode
): string {
  return crypto
    .createHash('sha1')
    .update(
      `v2|${mode}|${path.resolve(srcPath)}|${stat.size}|${Math.floor(stat.mtimeMs)}|${nums.join(',')}`
    )
    .digest('hex')
    .slice(0, 10)
}

/**
 * Create (or reuse) the SkinOverride files for a skin package.
 *
 * `companion` (default, for .fantome/.zip): a tiny extra mod holding only the added bins. Apply
 * it together with the ORIGINAL package, which is never copied or touched. `full`: one
 * standalone package (original + added bins), used for raw .wad files and for files you want to
 * hand to another launcher.
 *
 * Output goes to `cacheDir` under a name that embeds a content key, so a changed source package
 * or skin list automatically gets a fresh import in cslol-tools.
 */
export async function createSkinOverrideVariant(
  srcPath: string,
  options: SkinOverrideOptions
): Promise<SkinOverrideReport> {
  const notApplicable = (reason: string): SkinOverrideReport => ({
    applicable: false,
    reason,
    generated: 0,
    mode: 'full',
    outputPath: srcPath
  })

  try {
    await ensureXXHashReady()
    const compress: Compressor = zstdCompress
    const lower = srcPath.toLowerCase()
    const isWad = lower.endsWith('.wad.client') || lower.endsWith('.wad')
    const isZip = lower.endsWith('.fantome') || lower.endsWith('.zip')
    if (!isWad && !isZip) return notApplicable('unsupported file type')

    // raw .wad files have no package name to build a companion from: they get a full copy
    const wantCompanion = (options.mode ?? 'companion') === 'companion' && isZip
    const mode: SkinOverrideMode = wantCompanion ? 'companion' : 'full'
    const skinNums = [...new Set(options.skinNums?.length ? options.skinNums : DEFAULT_SKIN_RANGE)]
      .filter((n) => Number.isInteger(n) && n > 0 && n < 1000)
      .sort((a, b) => a - b)
    const hints = options.championKey ? [options.championKey] : []

    const stat = await fs.stat(srcPath)
    const key = cacheKey(srcPath, stat, skinNums, mode)
    const base = path.basename(srcPath).replace(/\.(wad\.client|wad|fantome|zip)$/i, '')
    const outName =
      mode === 'companion'
        ? `${base}.sl-${key}.companion.fantome`
        : isWad
          ? `${base}.sl-${key}${lower.endsWith('.wad.client') ? '.wad.client' : '.wad'}`
          : `${base}.sl-${key}${path.extname(srcPath)}`
    const outputPath = path.join(options.cacheDir, outName)

    // Reuse a previous run (an empty marker records "not applicable" results)
    try {
      await fs.access(outputPath)
      return { applicable: true, generated: 0, cached: true, mode, outputPath }
    } catch {
      /* not cached yet */
    }
    try {
      await fs.access(outputPath + '.na')
      return notApplicable('no skin0 bins in package (cached)')
    } catch {
      /* not cached yet */
    }

    await fs.mkdir(options.cacheDir, { recursive: true })
    const finish = async (data: Buffer): Promise<void> => {
      await fs.writeFile(outputPath + '.tmp', data)
      await fs.rename(outputPath + '.tmp', outputPath)
    }
    const markNotApplicable = async (reason: string): Promise<SkinOverrideReport> => {
      await fs.writeFile(outputPath + '.na', reason)
      return notApplicable(reason)
    }
    let report: SkinOverrideReport

    if (isWad) {
      const res = await withFileRange(srcPath, 0, stat.size, (src) =>
        buildFullWad(src, skinNums, hints, compress)
      )
      if (!res.wad) return await markNotApplicable(res.reason ?? 'not applicable')
      await finish(res.wad)
      report = {
        applicable: true,
        generated: res.generated,
        sourceSkinNum: res.sourceSkinNum,
        mode,
        outputPath
      }
    } else if (mode === 'companion') {
      const results = await forEachZipWad(srcPath, async (name, src) => ({
        name,
        res: await buildCompanionWad(src, skinNums, hints, compress)
      }))
      const hits = results.filter((r) => r.res.wad)
      if (hits.length === 0) {
        return await markNotApplicable(results[0]?.res.reason ?? 'no skin0 bins in package')
      }
      const info = {
        Name: `${base} (SkinOverride)`,
        Author: 'Bocchi SkinOverride',
        Version: '1.0.0',
        Description: `Companion of "${base}": lets it show over any equipped skin. Apply together with the original.`
      }
      await finish(
        writeStoreZip([
          { name: 'META/info.json', data: Buffer.from(JSON.stringify(info, null, 2)) },
          ...hits.map((h) => ({ name: h.name, data: h.res.wad as Buffer }))
        ])
      )
      report = {
        applicable: true,
        generated: hits.reduce((sum, h) => sum + h.res.generated, 0),
        sourceSkinNum: hits.find((h) => h.res.sourceSkinNum !== undefined)?.res.sourceSkinNum,
        mode,
        outputPath
      }
    } else {
      const zip = new StreamZip.async({ file: srcPath })
      const inputs: ZipInputEntry[] = []
      let generated = 0
      let sourceSkinNum: number | undefined
      try {
        for (const entry of Object.values(await zip.entries())) {
          if (entry.isDirectory) continue
          const name = entry.name.replaceAll('\\', '/')
          // cslol-tools' fantome importer rejects anything under META/hashes
          if (name.toUpperCase().startsWith('META/HASHES/')) continue
          let data: Buffer = Buffer.from(await zip.entryData(entry))
          if (name.toUpperCase().startsWith('WAD/') && /\.WAD(\.CLIENT)?$/i.test(name)) {
            const res = await buildFullWad(bufferSource(data), skinNums, hints, compress)
            if (res.wad) {
              data = res.wad
              generated += res.generated
              sourceSkinNum = res.sourceSkinNum ?? sourceSkinNum
            }
          }
          inputs.push({ name, data })
        }
      } finally {
        await zip.close()
      }
      if (generated === 0) return await markNotApplicable('no skin0 bins in package')
      await finish(writeStoreZip(inputs))
      report = { applicable: true, generated, sourceSkinNum, mode, outputPath }
    }

    console.log(
      `[SkinOverride] ${path.basename(srcPath)}: +${report.generated} bins (${mode})` +
        (report.sourceSkinNum !== undefined ? ` (rebased from skin${report.sourceSkinNum})` : '')
    )
    return report
  } catch (err) {
    console.warn(`[SkinOverride] Failed for ${srcPath}:`, err)
    return notApplicable('error: ' + (err instanceof Error ? err.message : String(err)))
  }
}

/**
 * Every skin and chroma index a champion has, from the champion data Bocchi already caches.
 * Chroma ids are `championId * 1000 + skinIndex`, so the index is `id % 1000`.
 * Returns undefined for unknown champions (e.g. "Custom"), which makes SkinOverride use its
 * default range.
 */
export async function getSkinNumsForChampion(championKey: string): Promise<number[] | undefined> {
  try {
    const champion = await championDataService.getChampionByKey(championKey)
    if (!champion) return undefined
    const nums = new Set<number>()
    for (const skin of champion.skins) {
      nums.add(skin.num)
      for (const chroma of skin.chromaList ?? []) nums.add(chroma.id % 1000)
    }
    nums.delete(0)
    return nums.size > 0 ? [...nums] : undefined
  } catch {
    return undefined
  }
}

/**
 * Build the SkinOverride files for a batch of resolved skin files (used right before applying).
 * Returns originalPath -> the list of paths to apply instead: `[original, companion]` for
 * packages (the original stays untouched), or `[standalone copy]` for raw wads. Callers fall
 * back to the original path for everything else. Items with `enabled: false` are skipped.
 */
export async function resolveSkinOverridePaths(
  items: Array<{ localPath?: string | null; championKey?: string; enabled?: boolean }>
): Promise<Map<string, string[]>> {
  const cacheDir = path.join(app.getPath('userData'), 'skin-override-cache')
  const out = new Map<string, string[]>()
  await Promise.all(
    items.map(async ({ localPath, championKey, enabled = true }) => {
      if (!localPath || !enabled) return
      const known = !!championKey && championKey !== 'Custom'
      const report = await createSkinOverrideVariant(localPath, {
        championKey: known ? championKey : undefined,
        skinNums: known ? await getSkinNumsForChampion(championKey!) : undefined,
        cacheDir
      })
      if (report.applicable) {
        out.set(
          localPath,
          report.mode === 'companion' ? [localPath, report.outputPath] : [report.outputPath]
        )
      }
    })
  )
  return out
}

/**
 * Cheap check used by the UI: can SkinOverride do anything with this package?
 * False for mods that are not rebased skins (no skin0 bins), e.g. texture or sound mods.
 * Only reads the WAD header and the small bins, never the whole mod.
 */
type Inspection = { applicable: boolean; reason?: string; sourceSkinNum?: number }
const inspectCache = new Map<string, Inspection>()

export async function inspectSkinOverride(srcPath: string, championKey?: string): Promise<Inspection> {
  try {
    const stat = await fs.stat(srcPath)
    const cacheId = `${srcPath}|${stat.size}|${Math.floor(stat.mtimeMs)}|${championKey ?? ''}`
    const cached = inspectCache.get(cacheId)
    if (cached) return cached
    const result = await inspectUncached(srcPath, championKey)
    inspectCache.set(cacheId, result)
    return result
  } catch (err) {
    return {
      applicable: false,
      reason: 'error: ' + (err instanceof Error ? err.message : String(err))
    }
  }
}

async function inspectUncached(srcPath: string, championKey?: string): Promise<Inspection> {
  try {
    await ensureXXHashReady()
    const lower = srcPath.toLowerCase()
    const hints = championKey && championKey !== 'Custom' ? [championKey] : []
    let scans: Array<WadScan | { reason: string }>
    if (lower.endsWith('.wad.client') || lower.endsWith('.wad')) {
      const stat = await fs.stat(srcPath)
      scans = [await withFileRange(srcPath, 0, stat.size, (src) => scanWad(src, hints))]
    } else if (lower.endsWith('.fantome') || lower.endsWith('.zip')) {
      scans = await forEachZipWad(srcPath, (_name, src) => scanWad(src, hints))
    } else {
      return { applicable: false, reason: 'unsupported file type' }
    }
    for (const scan of scans) {
      if (!('reason' in scan)) return { applicable: true, sourceSkinNum: scan.sourceSkinNum }
    }
    return { applicable: false, reason: 'no skin0 bins in package' }
  } catch (err) {
    return {
      applicable: false,
      reason: 'error: ' + (err instanceof Error ? err.message : String(err))
    }
  }
}
